export function merchantStatusLabel(status: NitipMerchantProfile["status"], language: NitipLanguage) {
  const labels = language === "en"
    ? { draft: "DRAFT", pending_review: "UNDER REVIEW", approved: "ACTIVE", rejected: "REJECTED" }
    : { draft: "DRAFT", pending_review: "MENUNGGU REVIEW", approved: "AKTIF", rejected: "DITOLAK" };
  return labels[status];
}

